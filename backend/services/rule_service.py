    # if threshold_value is not None:
    #     rule.threshold_value = threshold_value
    # if score is not None:
    #     rule.score = score
    # if window_minutes is not None:
    #     rule.window_minutes = window_minutes
    #instead of above commented code, we can use setattr to update the attributes dynamically based on the keys in the update_data dictionary. This way, we can avoid writing multiple if statements for each attribute.

    effective_signal_key = update_data.get(
        "signal_key",
        rule.signal_key,
    )

    effective_operator = update_data.get(
        "operator",
        rule.operator,
    )

    effective_comparison_value = update_data.get(
        "comparison_value",
        rule.comparison_value,
    )

    effective_window_minutes = update_data.get(
        "window_minutes",
        rule.window_minutes,
    )

    if (
        effective_signal_key is not None
        and effective_operator is not None
        and effective_comparison_value is not None
    ):
        validate_rule_configuration(
            signal_key=effective_signal_key,
            operator=effective_operator,
            comparison_value=effective_comparison_value,
            window_minutes=effective_window_minutes,
        )

    for field, value in update_data.items():
        setattr(rule, field, value)

    db.commit()
    db.refresh(rule)
    return rule
