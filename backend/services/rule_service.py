from sqlalchemy.orm import Session
from backend import models
from backend.signals.signal_registry import (is_operator_allowed, is_comparison_value_valid, get_signal_definition)
from backend.schemas import FraudRuleCreate

def generate_rule_key(rule_name: str) -> str:
    return (
        rule_name.strip()
        .lower()
        .replace(" ", "_")
    )

def get_rule(
    db: Session,
    rule_key: str,
) -> models.FraudRule | None:
    return (
        db.query(models.FraudRule)
        .filter(models.FraudRule.rule_key == rule_key)
        .first()
    )

def get_all_rules(
    db: Session,
    limit:int,
    offset:int
) -> list[models.FraudRule]:
    return (
        db.query(models.FraudRule)
        .order_by(models.FraudRule.rule_name.asc())
        .offset(offset)
        .limit(limit)   
        .all()
    )

## Helper function to validate rule parameters.
def validate_rule_configuration(
    signal_key: str,
    operator: str,
    comparison_value: int | float | bool,
    window_minutes: int | None,
) -> None:
    signal_definition = get_signal_definition(signal_key)

    if not is_operator_allowed(signal_key, operator):
        raise ValueError(
            f"Operator '{operator}' is not allowed "
            f"for signal '{signal_key}'."
        )

    if not is_comparison_value_valid(
        signal_key,
        comparison_value,
    ):
        raise ValueError(
            f"Comparison value '{comparison_value}' is not valid "
            f"for signal '{signal_key}'."
        )

    if (
        not signal_definition.uses_window
        and window_minutes is not None
    ):
        raise ValueError(
            f"Signal '{signal_key}' does not use a window."
        )

    if (
        signal_definition.uses_window
        and window_minutes is None
    ):
        raise ValueError(
            f"Signal '{signal_key}' requires window_minutes."
        )

def create_rule(
        db: Session,
        rule_data: FraudRuleCreate
) -> models.FraudRule:
    
    rule_key = generate_rule_key(rule_data.rule_name)

    existing_rule = (
        db.query(models.FraudRule)
        .filter(
            (models.FraudRule.rule_name == rule_data.rule_name)
            | (models.FraudRule.rule_key == rule_key)
        )
        .first()
    )

    if existing_rule:
        raise ValueError(
            "A rule with this name already exists."
        )

    validate_rule_configuration(
        signal_key=rule_data.signal_key,
        operator=rule_data.operator,
        comparison_value=rule_data.comparison_value,
        window_minutes=rule_data.window_minutes,
    )

    db_rule = models.FraudRule(
        rule_key = rule_key,
        **rule_data.model_dump()
    )

    db.add(db_rule)
    db.commit()
    db.refresh(db_rule)

    return db_rule

